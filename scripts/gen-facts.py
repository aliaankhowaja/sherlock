"""Print headline evaluation numbers from docs/eval/results.json as markdown.

Run from anywhere: python -I scripts/gen-facts.py
Redirect to docs/eval/facts.md to refresh it. Stdlib only; reads fields that exist, invents none.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(ROOT, "docs", "eval", "results.json")


def main():
    with open(RESULTS, encoding="utf-8") as f:
        d = json.load(f)
    allm = d["summary"]["all"]
    trials = d["trials"]
    print("Generated by scripts/gen-facts.py from docs/eval/results.json. Do not edit by hand.")
    print()
    print("Headline numbers over all cases (summary.all). `exact` = the prediction equals the gold collection, `wrong` = it names sets that differ, `abstain` = no claim (see docs/eval/README.md).")
    print()
    print("| Method | Cases | Exact | Wrong | Abstain |")
    print("|---|---|---|---|---|")
    order = ["sherlock"] + sorted(k for k in allm if k != "sherlock")
    for name in order:
        m = allm[name]
        print("| %s | %d | %d | %d | %d |" % (name, m["n"], m["exact"], m["wrong"], m["abstain"]))
    print()
    print("Trials on cases where Sherlock found an answer (trials): %d used against %d exhaustive subsets (fewer_pct %s)."
          % (trials["used_on_found"], trials["exhaustive_on_found"], trials["fewer_pct"]))
    print()
    print("Retry check (retry): %d runs per case; cases where a retry passed: %d."
          % (d["retry"]["runs_per_case"], d["retry"]["cases_where_a_retry_passed"]))


if __name__ == "__main__":
    main()
